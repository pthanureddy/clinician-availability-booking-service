CREATE TABLE IF NOT EXISTS mutation_lock (id INTEGER PRIMARY KEY);
INSERT INTO mutation_lock SELECT 1 WHERE NOT EXISTS (SELECT 1 FROM mutation_lock WHERE id=1);
CREATE TABLE IF NOT EXISTS slots (
 id VARCHAR(40) PRIMARY KEY, clinician VARCHAR(40) NOT NULL, market VARCHAR(2) NOT NULL,
 specialty VARCHAR(30) NOT NULL, language VARCHAR(10) NOT NULL,
 starts TIMESTAMP WITH TIME ZONE NOT NULL, ends TIMESTAMP WITH TIME ZONE NOT NULL,
 CHECK (ends > starts)
);
CREATE TABLE IF NOT EXISTS bookings (
 id VARCHAR(40) PRIMARY KEY, patient VARCHAR(60) NOT NULL, slot_id VARCHAR(40) NOT NULL REFERENCES slots(id),
 market VARCHAR(2) NOT NULL, specialty VARCHAR(30) NOT NULL, language VARCHAR(10) NOT NULL,
 active BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS operations (
 op_key VARCHAR(60) PRIMARY KEY, fingerprint VARCHAR(500) NOT NULL, booking_id VARCHAR(40) NOT NULL
);
